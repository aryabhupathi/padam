def expand():
    lex_path = os.path.join(os.path.dirname(__file__), "telugu_lexicon.json")
    with open(lex_path, "r", encoding="utf-8") as f:
        existing = json.load(f)
    
    seen = {entry["word"]: entry for entry in existing}
    added = 0
    for w, clue, cat in NEW_WORDS:
        w = w.strip()
        if not is_valid_telugu_word(w): continue
        if w in seen: continue
        syls = split_into_syllables(w)
        entry = {
            "word": w,
            "syllables": syls,
            "length": len(syls),
            "clue": clue.strip(),
            "category": cat.strip()
        }
        existing.append(entry)
        seen[w] = entry
        added += 1

    with open(lex_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    print(f"Added {added} new rich words! Total words now: {len(existing)}")

if __name__ == "__main__":
    expand()
