def expand():
    lex_path = os.path.join(os.path.dirname(__file__), "..", "data", "telugu_lexicon.json")
    with open(lex_path, "r", encoding="utf-8") as f:
        existing = json.load(f)

    existing_words = {w["word"]: w for w in existing}
    initial_count = len(existing_words)
    added = 0

    for word, clue, cat in NEW_WORDS:
        word = word.strip()
        if word not in existing_words:
            syls = split_into_syllables(word)
            if len(syls) >= 2:
                entry = {
                    "word": word,
                    "syllables": syls,
                    "clue": clue,
                    "category": cat
                }
                existing.append(entry)
                existing_words[word] = entry
                added += 1

    with open(lex_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    print(f"Expanded lexicon: started with {initial_count}, added {added}, total {len(existing)}")

if __name__ == "__main__":
    expand()
