def build_lexicon():
    print("Building master lexicon...")
    seen = set()
    cleaned_entries = []

    for item in VOCAB_LIST:
        word, clue, cat = item[0].strip(), item[1].strip(), item[2].strip()
        if not word or not is_valid_telugu_word(word):
            print(f"Skipping invalid word: {word}")
            continue
        if word in seen:
            continue
        seen.add(word)
        syls = split_into_syllables(word)
        cleaned_entries.append({
            "word": word,
            "syllables": syls,
            "length": len(syls),
            "clue": clue,
            "category": cat
        })

    out_path = os.path.join(os.path.dirname(__file__), "telugu_lexicon.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(cleaned_entries, f, ensure_ascii=False, indent=2)

    print(f"Successfully generated master lexicon with {len(cleaned_entries)} words at {out_path}!")

if __name__ == "__main__":
    build_lexicon()
